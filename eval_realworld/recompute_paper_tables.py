"""
Deterministic, reproducible recomputation of the real-world tabular benchmark's
final per-(dataset, model) accuracy/F1 table (paper Table 9 and Table 10) and the
cross-dataset Wilcoxon signed-rank test with Bonferroni correction (paper Section 6
"Conclusions" and Section 5.3.B "Real ML Datasets (Tabular)").

Why this script exists
-----------------------
The version of these tables/statistics that first went into the manuscript was
assembled through an ad hoc, LLM-assisted comparison of the per-dataset
`fewshot_results.csv` files, rather than a fixed, versioned procedure. That process
(a) silently dropped Iris from the real-world dataset pool, and (b) left the final
cross-dataset Wilcoxon test uncorrected for the 16 pairwise comparisons against the
leader model, despite Section 4.6.2 of the paper describing a Bonferroni correction.
This script replaces that step with a fixed, documented, and re-runnable procedure so
that Table 9, Table 10, and the associated significance claims in the manuscript can
be regenerated by anyone from the raw per-seed results.

Rule (fixed and documented, decided independently of the specific numbers it produces)
---------------------------------------------------------------------------------------
1. For each of the 12 real-world datasets (Iris included), restrict to rows where
   `aggregation_level == "seed_summary"`, `protocol == "sample_disjoint"`,
   `with_tuning == True`, and `status == "ok"` -- the tuned, sample-disjoint episodic
   protocol used for the paper's headline results.
2. Identify that dataset's "canonical" episodic configuration as the `fewshot_config`
   value shared by the largest number of distinct reduction-method CSVs (i.e., the
   configuration most reduction methods actually landed in via the automatic N/K/Q
   adaptation rule in Section 4.4). This avoids mixing episode-difficulty settings
   that differ because an aggressive reduction method (e.g. DROP3, PSC) forced a
   smaller N/K/Q for just that one reduction variant.
3. Within that canonical configuration, for each model, take the MAXIMUM seed-averaged
   accuracy/F1 (`acc_mean` / `f1_mean`) across the available reduction-method variants
   -- matching the "Best CL"/"Best FSL" framing the paper's Table 10 already used.
4. Assemble a 12-dataset x 17-model accuracy/F1 table (Table 9 = the global ranking by
   mean accuracy across all 12 datasets; Table 10 = the best classical vs. best FSL
   model per dataset).
5. Identify the leader model (highest mean accuracy across all 12 datasets).
6. Run the two-tailed Wilcoxon signed-rank test (`scipy.stats.wilcoxon`,
   `zero_method="wilcox"`) pairing the leader's per-dataset accuracy against each other
   model's, over the datasets where both have a value (n=12 unless a model is missing
   data for some dataset).
7. Report BOTH the raw p-value and the Bonferroni-corrected p-value
   (`raw_p * (n_models - 1)`, capped at 1.0) -- the same correction formula already
   used in `evalGeneric.py`'s `build_benchmark_analysis_rows` for the *within-dataset*
   comparison across reduction methods, applied here at the cross-dataset level.

Usage
-----
    python recompute_paper_tables.py

Outputs (written next to this script):
    FINAL_acc_table.csv       -- 12 x 17 accuracy table
    FINAL_f1_table.csv        -- 12 x 17 F1 table
    FINAL_wilcoxon.csv        -- pairwise Wilcoxon results vs. the leader model
"""
import pandas as pd
import numpy as np
from scipy.stats import wilcoxon
from pathlib import Path

ROOT = Path(__file__).parent / "reduced_csv"

# (subfolder, n_features, n_way) -- n_features/n_way are reference metadata only,
# used for Table 10's F/N-W columns; they do not affect the computation.
FOLDERS = {
    "Iris": ("01_iris", 4, 3),
    "Wine": ("02_Wine", 13, 3),
    "Heart": ("03_HEART_DISEASE", 13, 2),
    "Pima": ("04_PIMA_INDIAN", 8, 2),
    "Ionosphere": ("05_Ionosphere", 34, 2),
    "BC_Wisconsin": ("06_BREAST CANCER WISCONSIN", 30, 2),
    "Penguins": ("07_PENGUINS", 9, 3),
    "Glass": ("08_GLASS", 9, 3),
    "Seeds": ("09_SEED", 7, 3),
    "Ecoli": ("10_ECOLI", 7, 4),
    "Vertebral": ("11_Vertebral", 6, 3),
    "Dermatology": ("12_DERMATOLOGY", 34, 3),
}

CL_MODELS = ["LogReg", "SVM_RBF", "kNN", "RandomForest", "MLP"]
FSL_MODELS = ["ProtoNet", "MatchingNet", "RelationNet", "CosineClassifier", "CovarianceNet",
              "TransductivePropagationNet", "SiameseNet"]
PE_MODELS = ["LogReg_ProtoEmb", "SVM_RBF_ProtoEmb", "kNN_ProtoEmb", "RandomForest_ProtoEmb", "MLP_ProtoEmb"]


def find_results_csv(folder: Path) -> Path:
    candidates = list(folder.glob("fewshot_results*.csv"))
    plain = [c for c in candidates if c.name == "fewshot_results.csv"]
    return plain[0] if plain else candidates[0]


def canonical_config_rows(csv_path: Path) -> pd.DataFrame:
    df = pd.read_csv(csv_path, low_memory=False)
    ss = df[(df["aggregation_level"] == "seed_summary")
            & (df["protocol"] == "sample_disjoint")
            & (df["with_tuning"] == True)
            & (df["status"] == "ok")].copy()
    config_counts = ss.groupby("fewshot_config")["dataset_label"].nunique()
    canonical = config_counts.idxmax()
    return ss[ss["fewshot_config"] == canonical]


def main():
    acc_rows, f1_rows, best_cl, best_fsl = {}, {}, {}, {}

    for name, (sub, feat, nway) in FOLDERS.items():
        main_rows = canonical_config_rows(find_results_csv(ROOT / sub))
        acc_rows[name] = main_rows.groupby("model")["acc_mean"].max().to_dict()
        f1_rows[name] = main_rows.groupby("model")["f1_mean"].max().to_dict()

        cl_acc = {m: acc_rows[name].get(m, np.nan) for m in CL_MODELS}
        best_cl_model = max(cl_acc, key=lambda k: (cl_acc[k] if not np.isnan(cl_acc[k]) else -1))
        fsl_acc = {m: acc_rows[name].get(m, np.nan) for m in FSL_MODELS}
        best_fsl_model = max(fsl_acc, key=lambda k: (fsl_acc[k] if not np.isnan(fsl_acc[k]) else -1))
        best_cl[name] = (best_cl_model, cl_acc[best_cl_model] * 100, f1_rows[name].get(best_cl_model, np.nan) * 100)
        best_fsl[name] = (best_fsl_model, fsl_acc[best_fsl_model] * 100, f1_rows[name].get(best_fsl_model, np.nan) * 100)

    acc_table = pd.DataFrame(acc_rows).T
    f1_table = pd.DataFrame(f1_rows).T

    print("=== Table 10: Best CL / Best FSL per dataset ===")
    for name, (sub, feat, nway) in FOLDERS.items():
        cl_m, cl_a, cl_f1 = best_cl[name]
        fsl_m, fsl_a, fsl_f1 = best_fsl[name]
        print(f"{name:14s} F={feat:2d} N-W={nway}  BestCL={cl_m:14s} {cl_a:5.1f}/{cl_f1:5.1f}   "
              f"BestFSL={fsl_m:14s} {fsl_a:5.1f}/{fsl_f1:5.1f}")
    print(f"\nMean Best-CL:  acc={np.mean([v[1] for v in best_cl.values()]):.1f}  "
          f"f1={np.mean([v[2] for v in best_cl.values()]):.1f}")
    print(f"Mean Best-FSL: acc={np.mean([v[1] for v in best_fsl.values()]):.1f}  "
          f"f1={np.mean([v[2] for v in best_fsl.values()]):.1f}")

    print("\n=== Table 9: global ranking (17 models, 12 datasets) ===")
    rank_acc = acc_table.mean(axis=0).sort_values(ascending=False)
    rank_f1 = f1_table.mean(axis=0)
    for i, (model, acc) in enumerate(rank_acc.items(), start=1):
        tag = "CL" if model in CL_MODELS else ("PE" if model in PE_MODELS else "FSL")
        print(f"{i:2d}  {model:28s} {tag:3s}  acc={acc * 100:5.2f}  f1={rank_f1[model] * 100:5.2f}")
    print(f"\nOverall mean: acc={rank_acc.mean() * 100:.2f}  f1={rank_f1.mean() * 100:.2f}")

    leader = rank_acc.index[0]
    n_models = acc_table.shape[1]
    comparison_count = n_models - 1
    print(f"\n=== Wilcoxon vs leader ({leader}), n_models={n_models}, comparisons={comparison_count} ===")
    results = []
    for model in acc_table.columns:
        if model == leader:
            continue
        pair = acc_table[[leader, model]].dropna()
        diffs = pair[model] - pair[leader]
        wins, losses = int(np.sum(diffs > 0)), int(np.sum(diffs < 0))
        try:
            stat, p = wilcoxon(pair[model], pair[leader], zero_method="wilcox", alternative="two-sided")
        except ValueError:
            stat, p = 0.0, np.nan
        p_bonf = min(1.0, p * comparison_count) if not np.isnan(p) else np.nan
        results.append({"model": model, "n": len(pair), "wins": wins, "losses": losses,
                         "mean_delta_pp": diffs.mean() * 100, "raw_p": p, "bonferroni_p": p_bonf})
    res_df = pd.DataFrame(results).sort_values("raw_p")
    pd.set_option("display.width", 160)
    print(res_df.round(4).to_string(index=False))
    print(f"\nSignificant after Bonferroni (p<0.05): {res_df[res_df['bonferroni_p'] < 0.05]['model'].tolist()}")

    out_dir = Path(__file__).parent
    acc_table.to_csv(out_dir / "FINAL_acc_table.csv")
    f1_table.to_csv(out_dir / "FINAL_f1_table.csv")
    res_df.to_csv(out_dir / "FINAL_wilcoxon.csv", index=False)
    print(f"\nSaved: {out_dir / 'FINAL_acc_table.csv'}")
    print(f"Saved: {out_dir / 'FINAL_f1_table.csv'}")
    print(f"Saved: {out_dir / 'FINAL_wilcoxon.csv'}")


if __name__ == "__main__":
    main()
